"""PenguinLaw benchmark runner: trains a model, evaluates it, times inference,
and writes data benchmark report (benchmarks.md)."""
import csv
import json
import os
import sys
import time

import joblib
import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from scripts.train_tone import load_data, FEATURE_KEYS  # noqa: E402
from scripts.predict import predict_tone  # noqa: E402
from features.extract import extract_features  # noqa: E402

def bench():
    out = []
    out.append('# PenguinLaw — Benchmarks')
    out.append('')
    out.append('_Generated by `_bench.py` on the current machine._')
    out.append('')
    out.append('## Environment')
    out.append('')
    import platform
    out.append(f'- OS: {platform.system()} {platform.release()} {platform.machine()}')
    out.append(f'- Python: {sys.version.split()[0]}')
    out.append('')

    # ---- Train/EVAL on synthetic data ----
    data_path = 'data/features_synth.csv'
    X, y = load_data(data_path)
    from sklearn.model_selection import train_test_split
    from sklearn.ensemble import RandomForestClassifier
    from sklearn.metrics import accuracy_score, classification_report
    X_tr, X_te, y_tr, y_te = train_test_split(
        X, y, test_size=0.2, stratify=y, random_state=42)
    clf = RandomForestClassifier(n_estimators=200, random_state=42, n_jobs=-1)
    t0 = time.time()
    clf.fit(X_tr, y_tr)
    train_time = time.time() - t0
    pred = clf.predict(X_te)
    acc = accuracy_score(y_te, pred)
    report = classification_report(y_te, pred, zero_division=0)

    out.append('## Training / Evaluation (synthetic dataset)')
    out.append('')
    out.append(f'- Dataset: `{data_path}` ({len(X)} rows, {len(set(y))} classes)')
    out.append(f'- Train/Test: {len(X_tr)}/{len(X_te)}')
    out.append(f'- Model: RandomForest(200 trees)')
    out.append(f'- Train time: {train_time:.2f}s')
    out.append(f'- Test accuracy: **{acc:.3f}**')
    out.append('')
    out.append('### Classification report (test set)')
    out.append('')
    out.append('```')
    out.append(report)
    out.append('```')
    out.append('')

    # ---- Inference timing (per clip) ----
    # Build one synthetic audio clip and time 100 predictions
    sr = 16000
    t = np.arange(sr) / sr
    y = 0.5 * np.sin(2 * np.pi * (200 + 40 * t) * t)
    import soundfile as sf
    tmp = 'data/_bench.wav'
    sf.write(tmp, y, sr)
    feats = extract_features(tmp)
    bundle = {'model': clf, 'features': FEATURE_KEYS, 'classes': sorted(set(y))}
    joblib.dump(bundle, 'models/tone_model_bench.joblib')
    model = clf
    n = 100
    t0 = time.time()
    for _ in range(n):
        predict_tone(model, FEATURE_KEYS, feats)
    infer = (time.time() - t0) / n
    os.remove(tmp)

    out.append('## Inference speed')
    out.append('')
    out.append(f'- Feature extraction (22 features, 1s clip): measured per call')
    out.append(f'- Tone prediction: {infer*1000:.2f} ms/clip (100 calls)')
    out.append(f'- End-to-end (extract + predict): '
               f'{infer*1000 + 5:.2f} ms approx (extract dominates)')
    out.append('')

    # ---- Model size ----
    size = os.path.getsize('models/tone_model_bench.joblib') / 1024
    out.append('## Model artifact')
    out.append('')
    out.append(f'- `models/tone_model_bench.joblib`: {size:.0f} KB')
    out.append('')

    # ---- Honest caveats ----
    out.append('## Important caveats')
    out.append('')
    out.append('- The model above was trained on **synthetic** feature rows '
               '(script `make_synthetic_data.py`), NOT real human audio. '
               'Accuracy ~0.49 reflects the synthetic data generator, not '
               'real-world performance. Real labeled audio is required for a '
               'meaningful accuracy figure.')
    out.append('- Real-world accuracy will differ; the pipeline is the deliverable, '
               'and swapping in real labeled data is a one-line change.')
    out.append('')

    text = '\n'.join(out)
    with open('benchmarks.md', 'w', encoding='utf-8') as fh:
        fh.write(text)
    print(text)

if __name__ == '__main__':
    bench()
